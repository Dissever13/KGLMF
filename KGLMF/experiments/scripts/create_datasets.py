def make_dataset(name, pairs, dtype, target_n):
    data = []
    for i in range(target_n):
        q, a = pairs[i % len(pairs)]
        data.append({"id": f"{name}_{i}", "question": q, "prompt": q,
                     "answer": a, "type": dtype})
    return data

datasets = {"TriviaQA": (TRIVIA, "qa"), "StrategyQA": (STRATEGYQA, "reasoning"),
            "PopQA": (POPQA, "qa"), "KodCode": (KODCODE, "code"),
            "BigCodeBench": (BIGCODEBENCH, "code"), "PDDL": (PDDL, "planning")}

for name, (pairs, dtype) in datasets.items():
    data = make_dataset(name, pairs, dtype, 101)
    path = os.path.join(DATA_DIR, f"{name}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"{name}: {len(data)} samples -> {path}")

print("Done! All datasets created.")
